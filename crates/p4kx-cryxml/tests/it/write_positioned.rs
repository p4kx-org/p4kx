use std::error::Error;
use std::ops::Range;

use p4kx_cryxml::{self as cryxml, XmlFieldKind, XmlRawKind, XmlRenderKind, XmlRenderSpan};
use p4kx_testkit::{CryXmlByteOrder, CryXmlSignature, TestElement};

type TestResult<T = ()> = Result<T, Box<dyn Error>>;

#[test]
fn positioned_xml_preserves_output_and_anchors_every_visible_run() -> TestResult {
    for order in [CryXmlByteOrder::Little, CryXmlByteOrder::Big] {
        let fixture = TestElement::new("r:oot")
            .attribute("dup", "a&b")
            .attribute("dup", "")
            .attribute("spaces", "a\nb")
            .content("one<&\n\nlast\r\n")
            .child(TestElement::new("leaf"))
            .to_cryxml(CryXmlSignature::CryXmlB, order);
        let render = render(&fixture)?;
        check_spans(&render)?;
        check_name_and_empty(&fixture, &render, order)?;
        check_text(&fixture, &render)?;
        check_structure(&fixture, &render, order)?;
    }
    Ok(())
}

fn check_spans(render: &Rendered) -> TestResult {
    let declaration = render.spans.first().ok_or("XML declaration span")?;
    assert_eq!(
        declaration.kind(),
        XmlRenderKind::Declaration,
        "synthetic XML prolog"
    );
    assert!(
        declaration.complete() && declaration.sources().next().is_none(),
        "the fixed prolog has no source bytes"
    );
    let mut previous = 0;
    for observed in &render.spans {
        let range = observed.range();
        assert_eq!(
            range.start, previous,
            "ordered span coverage including zero-width facts"
        );
        previous = range.end;
    }
    assert_eq!(
        previous,
        render.bytes.len() as u64,
        "every output byte has an event"
    );
    Ok(())
}

fn check_name_and_empty(fixture: &[u8], render: &Rendered, order: CryXmlByteOrder) -> TestResult {
    let original = find(render, XmlFieldKind::ElementName, b"r_oot")?;
    let (offset, raw) = fact(fixture, original, XmlRawKind::NodeNameOffset)?;
    let node_base = word(fixture, 12, order)?;
    let string_base = word(fixture, 36, order)?;
    assert_eq!(
        offset,
        u64::from(node_base),
        "the physical first node's name offset"
    );
    let (start, name) = fact(fixture, original, XmlRawKind::StringBytes)?;
    assert_eq!(
        start,
        u64::from(string_base) + u64::from(decode(raw, order)?),
        "the original offset selects these bytes"
    );
    assert_eq!(name, b"r:oot", "source before name sanitization");

    let duplicate = find(render, XmlFieldKind::AttributeName, b"dup_2")?;
    let (position, _) = fact(fixture, duplicate, XmlRawKind::AttributeNameOffset)?;
    assert_eq!(
        position,
        u64::from(word(fixture, 20, order)?) + 8,
        "second physical attribute"
    );
    let (_, raw) = fact(fixture, duplicate, XmlRawKind::StringBytes)?;
    assert_eq!(raw, b"dup", "suffix generated by serializer");
    let empty = find(render, XmlFieldKind::AttributeValue, b"")?;
    assert!(
        empty.range().is_empty() && empty.complete(),
        "author-present empty value"
    );
    let (_, raw) = fact(fixture, empty, XmlRawKind::StringTerminator)?;
    assert_eq!(raw, &[0], "the actual empty string NUL");
    assert!(
        empty
            .sources()
            .all(|use_| use_.kind() != XmlRawKind::StringBytes),
        "the empty value has no invented content bytes"
    );
    let line_break = find(render, XmlFieldKind::AttributeValue, b"a&#10;b")?;
    let (_, raw) = fact(fixture, line_break, XmlRawKind::StringBytes)?;
    assert_eq!(raw, b"a\nb", "an attribute newline is escaped on one line");
    Ok(())
}

fn check_text(fixture: &[u8], render: &Rendered) -> TestResult {
    for (xml, original) in [
        (b"one&lt;&amp;\n".as_slice(), b"one<&\n".as_slice()),
        (b"\n", b"\n"),
        (b"last&#13;\n", b"last\r\n"),
    ] {
        let span = find(render, XmlFieldKind::Text, xml)?;
        let (_, raw) = fact(fixture, span, XmlRawKind::StringBytes)?;
        assert_eq!(
            raw, original,
            "one authored LF section without neighboring text"
        );
        assert!(
            span.complete(),
            "the text conversion has exact original coordinates"
        );
    }
    Ok(())
}

fn check_structure(fixture: &[u8], render: &Rendered, order: CryXmlByteOrder) -> TestResult {
    let child_parent = u64::from(word(fixture, 12, order)?) + 28 + 12;
    let parent_fact = render
        .spans
        .iter()
        .filter(|span| span.kind() == XmlRenderKind::Structure && span.complete())
        .flat_map(XmlRenderSpan::sources)
        .any(|use_| use_.kind() == XmlRawKind::NodeParent && use_.range().start == child_parent);
    assert!(
        parent_fact,
        "actual child parent word used to select formatting"
    );
    let leaf = render
        .spans
        .iter()
        .find(|span| {
            span.kind() == XmlRenderKind::Structure
                && rendered(render, span.range()) == Some(b"/>\n")
        })
        .ok_or("self-closing rendering")?;
    assert!(
        !leaf.complete(),
        "the omission of children has no captured parent survey"
    );
    let (_, empty) = fact(fixture, leaf, XmlRawKind::StringTerminator)?;
    assert_eq!(
        empty,
        &[0],
        "the empty content decision is observed despite partial shape"
    );
    Ok(())
}

#[test]
fn positioned_xml_keeps_repaired_and_skipped_string_bytes_distinct() -> TestResult {
    let order = CryXmlByteOrder::Little;
    let mut invalid = TestElement::new("Root")
        .attribute("v", "xYz")
        .to_cryxml(CryXmlSignature::CryXmlB, order);
    let offset = invalid
        .windows(3)
        .position(|bytes| bytes == b"xYz")
        .ok_or("raw string")?;
    *invalid.get_mut(offset + 1).ok_or("repair byte")? = 0xff;
    let output = render(&invalid)?;
    let site = find(&output, XmlFieldKind::AttributeValue, b"x?z")?;
    let (_, raw) = fact(&invalid, site, XmlRawKind::StringBytes)?;
    assert_eq!(
        raw,
        &[b'x', 0xff, b'z'],
        "repair retains the original malformed byte coordinate"
    );

    let mut shifted = TestElement::new("Root")
        .attribute("v", "xéz")
        .to_cryxml(CryXmlSignature::CryXmlB, order);
    let attribute = usize::try_from(word(&shifted, 20, order)?)? + 4;
    let value = word(&shifted, attribute, order)? + 2;
    shifted
        .get_mut(attribute..attribute + 4)
        .ok_or("attribute value word")?
        .copy_from_slice(&value.to_le_bytes());
    let output = render(&shifted)?;
    let site = find(&output, XmlFieldKind::AttributeValue, b"z")?;
    let (selected, raw) = fact(&shifted, site, XmlRawKind::StringBytes)?;
    let (skipped, boundary) = fact(&shifted, site, XmlRawKind::StringBoundary)?;
    assert_eq!(raw, b"z", "content starts at the next character");
    assert_eq!(boundary, &[0xa9], "the actual skipped continuation byte");
    assert_eq!(
        selected,
        skipped + 1,
        "prefix and value are separate original facts"
    );
    Ok(())
}

#[test]
fn positioned_indent_uses_actual_ancestry_for_opening_and_closing_tags() -> TestResult {
    for order in [CryXmlByteOrder::Little, CryXmlByteOrder::Big] {
        let deep = TestElement::new("deep").child(TestElement::new("leaf"));
        let branch =
            TestElement::new("branch")
                .child(TestElement::new("neighbor"))
                .child(TestElement::new("carrier").child(
                    TestElement::new("level3").child(TestElement::new("level4").child(deep)),
                ));
        let fixture = TestElement::new("root")
            .child(TestElement::new("before"))
            .child(branch)
            .child(TestElement::new("after"))
            .to_cryxml(CryXmlSignature::CryXmlB, order);
        let output = render(&fixture)?;
        check_spans(&output)?;
        let parents = [(7, 6), (6, 5), (5, 4), (4, 2), (2, 0)];
        for line in [b"<deep>\n".as_slice(), b"</deep>\n"] {
            check_indentation(&fixture, &output, order, line, &parents)?;
        }
    }
    Ok(())
}

#[test]
fn positioned_indent_at_the_cap_uses_only_the_nearest_parent_words() -> TestResult {
    const MAX_INDENT_LEVELS: u32 = 64;
    const DEPTH: u32 = MAX_INDENT_LEVELS + 3;
    let order = CryXmlByteOrder::Little;
    let input = (0..DEPTH)
        .fold(TestElement::new("bottom"), |child, _| {
            TestElement::new("branch").child(child)
        })
        .to_cryxml(CryXmlSignature::CryXmlB, order);
    let output = render(&input)?;
    check_spans(&output)?;
    let parents: Vec<_> = (DEPTH - MAX_INDENT_LEVELS + 1..=DEPTH)
        .rev()
        .map(|node| (node, node - 1))
        .collect();
    check_indentation(&input, &output, order, b"<bottom/>\n", &parents)
}

fn check_indentation(
    input: &[u8],
    render: &Rendered,
    order: CryXmlByteOrder,
    line_after_indent: &[u8],
    parents: &[(u32, u32)],
) -> TestResult {
    let indent = render
        .spans
        .iter()
        .find(|span| {
            span.kind() == XmlRenderKind::Structure
                && rendered(render, span.range()).is_some_and(|bytes| {
                    bytes.len() == parents.len() * 2 && bytes.iter().all(|byte| *byte == b' ')
                })
                && usize::try_from(span.range().end)
                    .ok()
                    .and_then(|end| render.bytes.get(end..))
                    .is_some_and(|rest| rest.starts_with(line_after_indent))
        })
        .ok_or("positioned indentation before expected tag")?;
    assert!(indent.complete(), "all contributing parent words are known");
    assert_eq!(indent.sources().count(), parents.len(), "exact edge count");
    let node_table = u64::from(word(input, 12, order)?);
    for (fact, &(node, parent)) in indent.sources().zip(parents) {
        let start = node_table + u64::from(node) * 28 + 12;
        assert_eq!(
            fact.kind(),
            XmlRawKind::NodeParent,
            "indent evidence cites a parent word"
        );
        assert_eq!(fact.range(), &(start..start + 4), "actual physical node");
        assert_eq!(
            word(input, usize::try_from(start)?, order)?,
            parent,
            "the authored parent word"
        );
    }
    Ok(())
}

struct Rendered {
    bytes: Vec<u8>,
    spans: Vec<XmlRenderSpan>,
}

fn render(fixture: &[u8]) -> TestResult<Rendered> {
    let document = cryxml::parse(fixture)?;
    let mut baseline = Vec::new();
    document.write_xml(&mut baseline)?;
    let mut bytes = Vec::new();
    let mut spans = Vec::new();
    document.write_xml_positioned(&mut bytes, |span| {
        spans.push(span);
        Ok(())
    })?;
    assert_eq!(
        bytes, baseline,
        "positioned rendering has byte-for-byte parity"
    );
    Ok(Rendered { bytes, spans })
}

fn find<'render>(
    render: &'render Rendered,
    kind: XmlFieldKind,
    bytes: &[u8],
) -> TestResult<&'render XmlRenderSpan> {
    render
        .spans
        .iter()
        .find(|span| {
            span.kind() == XmlRenderKind::Field(kind)
                && rendered(render, span.range()) == Some(bytes)
        })
        .ok_or_else(|| "expected emitted XML field span".into())
}

fn rendered<'render>(render: &'render Rendered, range: &Range<u64>) -> Option<&'render [u8]> {
    render
        .bytes
        .get(usize::try_from(range.start).ok()?..usize::try_from(range.end).ok()?)
}

fn fact<'input>(
    input: &'input [u8],
    span: &XmlRenderSpan,
    kind: XmlRawKind,
) -> TestResult<(u64, &'input [u8])> {
    let original = span
        .sources()
        .find(|use_| use_.kind() == kind)
        .ok_or("expected original source fact")?;
    let range = original.range();
    Ok((
        range.start,
        input
            .get(usize::try_from(range.start)?..usize::try_from(range.end)?)
            .ok_or("source range within original input")?,
    ))
}

fn word(bytes: &[u8], start: usize, order: CryXmlByteOrder) -> TestResult<u32> {
    decode(bytes.get(start..start + 4).ok_or("header word")?, order)
}

fn decode(bytes: &[u8], order: CryXmlByteOrder) -> TestResult<u32> {
    let bytes = <[u8; 4]>::try_from(bytes)?;
    Ok(match order {
        CryXmlByteOrder::Little => u32::from_le_bytes(bytes),
        CryXmlByteOrder::Big => u32::from_be_bytes(bytes),
    })
}
