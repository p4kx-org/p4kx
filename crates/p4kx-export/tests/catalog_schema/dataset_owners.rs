use std::collections::BTreeMap;

/// The contract role of an output boundary.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) enum Owner {
    Definition,
    Configuration,
    Declaration,
    Placement,
    PlacementCoverage,
    Projection,
    Text,
    RootDataset,
    Curated,
    DocumentMetadata,
}

/// The serialized shape at an output boundary.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) enum Shape {
    Table,
    Array,
    Object,
    Scalar,
}

#[derive(Debug)]
pub(super) struct Entry {
    pub(super) owner: Owner,
    pub(super) shape: Shape,
}

struct Group {
    owner: Owner,
    prefix: &'static str,
    shape: Shape,
    members: &'static [&'static str],
}

