use p4kx_extraction::{SourceValue, SourcedValue};
use schemars::JsonSchema;
use serde::Serialize;

use crate::CatalogError;
use crate::catalog_read::authored_xml_tree::AuthoredXmlElement;
use crate::catalog_read::original::EntrySourceXml;
use crate::schema_fields::every_field_required;

/// A recognised attribute of a Subsumption event declaration.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, JsonSchema)]
#[serde(rename_all = "camelCase")]
#[schemars(extend("x-p4kx-vocabularyClass" = "control"))]
#[non_exhaustive]
pub enum SubsumptionEventField {
    /// Authored renaming permission.
    Renamable,
    /// Authored deletion permission.
    Deletable,
    /// Authored read-only flag.
    ReadOnly,
    /// Authored static flag.
    Static,
    /// Authored generation flag.
    AutoGenerated,
    /// Authored sibling-linkage flag.
    SiblingLinkage,
    /// Original propagation mode.
    PropagationType,
    /// Authored respondent limit.
    MaxRespondents,
    /// Authored volume value.
    Volume,
    /// Authored range value.
    Range,
    /// Authored exit-range value.
    ExitRange,
    /// Authored requirement for visual detection.
    RequiresVisual,
    /// Authored horizontal field of view.
    FovHorizontal,
    /// Authored vertical field of view.
    FovVertical,
    /// Authored focus time.
    FocusTime,
    /// Authored angular offset.
    AngularOffset,
    /// Original looked-at condition discriminator.
    BeingLookedAtCondition,
}

impl SubsumptionEventField {
    const ALL: &[Self] = &[
        Self::Renamable,
        Self::Deletable,
        Self::ReadOnly,
        Self::Static,
        Self::AutoGenerated,
        Self::SiblingLinkage,
        Self::PropagationType,
        Self::MaxRespondents,
        Self::Volume,
        Self::Range,
        Self::ExitRange,
        Self::RequiresVisual,
        Self::FovHorizontal,
        Self::FovVertical,
        Self::FocusTime,
        Self::AngularOffset,
        Self::BeingLookedAtCondition,
    ];

    const fn key(self) -> &'static str {
        match self {
            Self::Renamable => "Renamable",
            Self::Deletable => "Deletable",
            Self::ReadOnly => "ReadOnly",
            Self::Static => "Static",
            Self::AutoGenerated => "AutoGenerated",
            Self::SiblingLinkage => "SiblingLinkage",
            Self::PropagationType => "PropagationType",
            Self::MaxRespondents => "MaxRespondents",
            Self::Volume => "Volume",
            Self::Range => "Range",
            Self::ExitRange => "ExitRange",
            Self::RequiresVisual => "RequiresVisual",
            Self::FovHorizontal => "FOVHorizontal",
            Self::FovVertical => "FOVVertical",
            Self::FocusTime => "FocusTime",
            Self::AngularOffset => "AngularOffset",
            Self::BeingLookedAtCondition => "BeingLookedAtCondition",
        }
    }

    fn decode(self, raw: &str) -> SourceValue<SubsumptionEventValue> {
        let value = match self {
            Self::Renamable
            | Self::Deletable
            | Self::ReadOnly
            | Self::Static
            | Self::AutoGenerated
            | Self::SiblingLinkage
            | Self::RequiresVisual => match raw {
                text if text.eq_ignore_ascii_case("true") => {
                    Some(SubsumptionEventValue::Boolean(true))
                }
                text if text.eq_ignore_ascii_case("false") => {
                    Some(SubsumptionEventValue::Boolean(false))
                }
                _ => None,
            },
            Self::MaxRespondents | Self::BeingLookedAtCondition => {
                raw.parse().ok().map(SubsumptionEventValue::Integer)
            }
            Self::Volume
            | Self::Range
            | Self::ExitRange
            | Self::FovHorizontal
            | Self::FovVertical
            | Self::FocusTime
            | Self::AngularOffset => raw
                .parse::<f64>()
                .ok()
                .filter(|value| value.is_finite())
                .map(SubsumptionEventValue::Number),
            Self::PropagationType => Some(SubsumptionEventValue::Text(raw.to_owned())),
        };
        value.map_or(SourceValue::Invalid, SourceValue::Present)
    }
}

/// A typed control value whose original spelling remains in the authored document.
#[derive(Debug, PartialEq, Serialize, JsonSchema)]
#[serde(tag = "kind", content = "value", rename_all = "camelCase")]
#[non_exhaustive]
pub enum SubsumptionEventValue {
    /// Authored boolean.
    Boolean(bool),
    /// Authored integral value.
    Integer(i64),
    /// Finite interpretation of an authored numeric token.
    Number(f64),
    /// Original propagation token.
    Text(#[schemars(extend("x-gameText" = true))] String),
}

/// An individually sourced control of a Subsumption event.
#[derive(Debug, Serialize, JsonSchema)]
#[serde(rename_all = "camelCase")]
#[schemars(transform = every_field_required)]
pub struct SubsumptionEventControl {
    field: SubsumptionEventField,
    value: SourcedValue<SubsumptionEventValue>,
}

impl SubsumptionEventControl {
    /// Returns which source attribute this value interprets.
    #[must_use]
    pub const fn field(&self) -> SubsumptionEventField {
        self.field
    }

    /// Borrows the typed state and original source evidence.
    #[must_use]
    pub const fn value(&self) -> &SourcedValue<SubsumptionEventValue> {
        &self.value
    }
}

pub(super) fn read(
    xml: &EntrySourceXml<'_>,
    element: &AuthoredXmlElement,
) -> Result<Vec<SubsumptionEventControl>, CatalogError> {
    SubsumptionEventField::ALL
        .iter()
        .map(|&field| {
            let value = attribute(xml, element, field.key(), |raw| field.decode(raw))?;
            Ok(SubsumptionEventControl { field, value })
        })
        .collect()
}

pub(super) fn attribute<T>(
    xml: &EntrySourceXml<'_>,
    element: &AuthoredXmlElement,
    key: &str,
    decode: impl FnOnce(&str) -> SourceValue<T>,
) -> Result<SourcedValue<T>, CatalogError> {
    let mut declarations = element
        .declarations()
        .iter()
        .filter(|entry| entry.name().value().is_some_and(|name| name == key))
        .map(|entry| entry.value().value());
    let sources = xml.sources();
    let position = element.position().origin();
    let value = match (declarations.next(), declarations.next()) {
        (None, _) => sources.value_with_origins(SourceValue::Absent, &[position])?,
        (Some(value), None) => sources.value_with_origins(
            value
                .value()
                .map_or(SourceValue::Unreadable, |raw| decode(raw)),
            &[position, value.origin()],
        )?,
        (Some(first), Some(second)) => {
            let origins: Vec<_> = std::iter::once(position)
                .chain(
                    [first, second]
                        .into_iter()
                        .chain(declarations)
                        .map(SourcedValue::origin),
                )
                .collect();
            sources.value_with_origins(SourceValue::Invalid, &origins)?
        }
    };
    Ok(value)
}
